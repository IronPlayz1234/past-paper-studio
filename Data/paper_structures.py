def get_paper_structure(subject_code, paper_code, year_code):
    """
    Get exact paper structure for known papers
    
    Args:
        subject_code: e.g., "0620"
        paper_code: e.g., "42"
        year_code: e.g., "m21" (Feb/March 2021), "s23" (May/June 2023), "w24" (Oct/Nov 2024)
    
    Returns:
        dict with question structure or None if unknown
    """
    key = f"{year_code}_qp_{paper_code}"
    
    if subject_code == "0620" and key in CHEMISTRY_0620_PAPER4_STRUCTURES:
        return CHEMISTRY_0620_PAPER4_STRUCTURES[key]
    
    return None


def extract_paper_code(pdf_url):
    """
    Extract paper code from PDF URL or filename
    
    Args:
        pdf_url: URL like "https://.../0620_s25_qp_42.pdf" or filename "0620_s25_qp_42.pdf"
    
    Returns:
        dict with {"subject": "0620", "year_code": "s25", "paper": "42"} or None
    """
    import re
    
    # Extract from URL or filename
    from urllib.parse import unquote, urlsplit
    value = str(pdf_url or "").replace("\\", "/")
    path = urlsplit(value).path if "://" in value else value
    filename = unquote(path).rsplit("/", 1)[-1]
    
    # Pattern: CODE_YEAR_SEASON_PAPER (e.g., 0620_s25_qp_42, 0620_m21_qp_43)
    # Year codes like s25, m21, w23 include a letter and 2 digits
    match = re.match(r'(\d{4})_([a-z]\d{2})_qp_(\d{2})', filename, re.IGNORECASE)
    if match:
        return {
            "subject": match.group(1),
            "year_code": match.group(2).lower(),
            "paper": match.group(3),
        }
    
    # Try alternative pattern for different formats
    # e.g., 0620_s25_42 (without qp_)
    match = re.match(r'(\d{4})_([a-z]\d{2})_(\d{2})', filename, re.IGNORECASE)
    if match:
        return {
            "subject": match.group(1),
            "year_code": match.group(2).lower(),
            "paper": match.group(3),
        }
    
    return None


def generate_question_ids_from_structure(structure):
    """
    Generate question IDs from paper structure
    
    Cambridge IGCSE format:
    - If a part (e.g., 1a) has subparts (i, ii, iii), ONLY the subparts are answerable
    - If a part has NO subparts, the part itself is answerable
    
    Returns list like: ["1ai", "1aii", "1aiii", "1b", "2a", "2ai", ...]
    """
    question_ids = []
    
    for q_num, q_data in structure["questions"].items():
        # Add main question (but not all papers have a standalone main question)
        # Cambridge papers usually don't have standalone Q1, Q2 - they go straight to Q1(a)
        
        parts = q_data.get("parts", [])
        subparts = q_data.get("subparts", {})
        
        for part in parts:
            # Check if this part has subparts
            if part in subparts and subparts[part]:
                # Part has subparts - ONLY add the subparts as answerable questions
                # e.g., for "1a(i)", "1a(ii)", we add "1ai", "1aii" but NOT "1a"
                for sub in subparts[part]:
                    sub_q_id = f"{q_num}{part}{sub}"
                    question_ids.append(sub_q_id)
            else:
                # Part has NO subparts - the part itself is answerable
                # e.g., "1b" has no subparts, so "1b" is an answerable question
                q_id = f"{q_num}{part}"
                question_ids.append(q_id)
    
    return question_ids


def calculate_marks_from_structure(structure, question_ids):
    """
    Calculate marks for each question from structure
    
    Cambridge IGCSE format:
    - If a part has subparts, marks are distributed among subparts (NOT part itself)
    - If a part has no subparts, part gets all its allocated marks
    
    NOTE: This is an approximation. Actual marks depend on Cambridge marking schemes.
    For AI grading, marks are determined by the AI model based on answer quality.
    
    Args:
        structure: Paper structure dict
        question_ids: List of question IDs
    
    Returns:
        dict mapping question_id to marks
    """
    question_marks = {}
    
    for q_num, q_data in structure["questions"].items():
        total_marks = q_data.get("marks", 0)
        parts = q_data.get("parts", [])
        q_subparts = q_data.get("subparts", {})
        
        if not parts:
            # No parts - question doesn't exist as standalone
            continue
        
        # Calculate average marks per part
        parts_with_subparts = sum(1 for p in parts if p in q_subparts and q_subparts[p])
        parts_without_subparts = len(parts) - parts_with_subparts
        
        total_subparts = sum(len(q_subparts.get(p, [])) for p in parts if p in q_subparts)
        total_items = parts_without_subparts + total_subparts
        
        if total_items > 0:
            avg_marks = total_marks / total_items
        else:
            avg_marks = 2
        
        # Assign marks to each part/subpart (keep as float for accuracy)
        for part in parts:
            if part in q_subparts and q_subparts[part]:
                # Part has subparts - distribute marks among subparts (NOT part itself)
                part_subs = q_subparts[part]
                for sub in part_subs:
                    sub_id = f"{q_num}{part}{sub}"
                    question_marks[sub_id] = avg_marks
                # Part itself does NOT get marks (only subparts are answerable)
            else:
                # Part has no subparts - part itself is answerable
                part_id = f"{q_num}{part}"
                question_marks[part_id] = avg_marks
    
    return question_marks
